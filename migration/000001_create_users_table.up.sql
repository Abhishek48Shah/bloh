CREATE TABLE IF NOT EXISTS users (id INT IDENTITY GENERATED ALWAYS AS PRIMARY KEY,username TEXT NOT NULL,email VARCHAR(255) UNIQUE NOT NULL,password TEXT NOT NULL,created_at TIMESTAMPTZ DEFAULT NOW(),update_at);
CREATE OR REPLACE FUNCTION user_updated()
REURN TRIGGER AS $$
BEGIN 
NEW.update_at = NOW();
RETURN NEW
END;
$$ LANGUAGE plpsql;
CREATE TRIGGER set_timestamp
BEFORE UPDATE ON users
FOR EACH ROW 
EXECUTE FUNCTION user_update();
